import { readFileSync, writeFileSync } from 'node:fs';
import { inflateSync } from 'node:zlib';
import { describe, expect, it } from 'vitest';
import { HEAD, HELD } from './anchors';
import { HEAD_FIX, headOf } from './anchorFix';
import { ACCESSORIES, BUDDIES } from './roster';

// The head anchors (plan §16.3): worked out from the sprites themselves, so a new pose or a redrawn one can't keep a stale
// anchor. `UPDATE_ANCHORS=1 npx vitest run src/domain/buddies/anchors.test.ts` writes anchors.ts again from public/buddies/.
// The check grid (ui/buddies/AnchorGrid, at ?check=anchors) is where they're read by eye.

const DIR = new URL('../../../public/buddies/', import.meta.url);

/** A non-interlaced 8-bit RGBA PNG (every Tiny sprite is one), as rows of alpha. */
function alphaOf(file: URL): { w: number; h: number; a: (x: number, y: number) => number } {
  const d = readFileSync(file);
  const w = d.readUInt32BE(16), h = d.readUInt32BE(20);
  if (d[24] !== 8 || d[25] !== 6 || d[28] !== 0) throw new Error(`${file}: not 8-bit RGBA`);
  const idat: Buffer[] = [];
  for (let i = 8; i < d.length;) {
    const len = d.readUInt32BE(i), type = d.toString('latin1', i + 4, i + 8);
    if (type === 'IDAT') idat.push(d.subarray(i + 8, i + 8 + len));
    i += 12 + len;
  }
  const raw = inflateSync(Buffer.concat(idat)), bpp = 4, stride = w * bpp, px = new Uint8Array(h * stride);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)], row = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? px[y * stride + x - bpp] : 0, b = y ? px[(y - 1) * stride + x] : 0, c = x >= bpp && y ? px[(y - 1) * stride + x - bpp] : 0;
      const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
      const pred = f === 0 ? 0 : f === 1 ? a : f === 2 ? b : f === 3 ? (a + b) >> 1 : pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      px[y * stride + x] = (row[x] + pred) & 255;
    }
  }
  return { w, h, a: (x, y) => px[y * stride + x * 4 + 3] };
}

/**
 * Where a head item sits: y is the top edge of the top-most opaque pixels, x the middle of the opaque run across the top three
 * rows (one ear or antenna alone doesn't pull a cap off centre). Sprite pixels, 0 at the top left; x to the half pixel.
 */
export function headAnchor(file: URL): [number, number] {
  const { w, h, a } = alphaOf(file);
  const solid = (x: number, y: number) => a(x, y) >= 128;
  let top = 0;
  while (top < h && !Array.from({ length: w }, (_, x) => solid(x, top)).some(Boolean)) top++;
  if (top === h) throw new Error(`${file}: empty`);
  let lo = w, hi = -1;
  for (let y = top; y < Math.min(h, top + 3); y++) for (let x = 0; x < w; x++) if (solid(x, y)) { lo = Math.min(lo, x); hi = Math.max(hi, x); }
  return [Math.round(lo + hi + 1) / 2, top];
}

/**
 * Where a held item rests on a head: y is the bottom edge of its bottom-most opaque pixels, x the middle of the opaque run across
 * its bottom three rows (a sword's grip, a hammer's handle). Sprite pixels, as headAnchor.
 */
export function heldBase(file: URL): [number, number] {
  const { w, h, a } = alphaOf(file);
  const solid = (x: number, y: number) => a(x, y) >= 128;
  let bottom = h - 1;
  while (bottom >= 0 && !Array.from({ length: w }, (_, x) => solid(x, bottom)).some(Boolean)) bottom--;
  if (bottom < 0) throw new Error(`${file}: empty`);
  let lo = w, hi = -1;
  for (let y = bottom; y > Math.max(-1, bottom - 3); y--) for (let x = 0; x < w; x++) if (solid(x, y)) { lo = Math.min(lo, x); hi = Math.max(hi, x); }
  return [Math.round(lo + hi + 1) / 2, bottom + 1];
}

const poses = BUDDIES.flatMap((b) => b.poses);
const items = ACCESSORIES.filter((x) => x.sprite).map((x) => x.id);

describe('head anchors', () => {
  const found = Object.fromEntries(poses.map((p) => [p, headAnchor(new URL(`${p}.png`, DIR))]));
  const bases = Object.fromEntries(items.map((p) => [p, heldBase(new URL(`${p}.png`, DIR))]));
  if (process.env.UPDATE_ANCHORS) {
    writeFileSync(new URL('./anchors.ts', import.meta.url), [
      '// GENERATED by anchors.test.ts from public/buddies/*.png (UPDATE_ANCHORS=1); edit the sprites, not this. Hand fixes: anchorFix.ts.',
      '/** Each pose\'s head anchor, in sprite pixels from the top left: [x, y], x to the half pixel. */',
      'export const HEAD: Readonly<Record<string, readonly [number, number]>> = {', ...poses.map((p) => `  ${p}: [${found[p].join(', ')}],`), '};',
      '/** Each held item\'s base: where it rests on a head anchor, [x, y] in its own sprite pixels (y its bottom edge). */',
      'export const HELD: Readonly<Record<string, readonly [number, number]>> = {', ...items.map((p) => `  ${p}: [${bases[p].join(', ')}],`), '};', ''].join('\n'));
  }
  it('every pose of every buddy has its sprite and the anchor worked out from it', () => {
    expect(Object.keys(HEAD).sort()).toEqual([...poses].sort());
    for (const p of poses) expect([p, ...HEAD[p]]).toEqual([p, ...found[p]]);
  });
  it('sits on the sprite: inside its 16 px and on an opaque pixel row', () => {
    for (const p of poses) { const [x, y] = HEAD[p]; expect(x > 0 && x < 16 && y >= 0 && y < 16, p).toBe(true); }
  });
  it('every held item has its base, worked out from its sprite', () => {
    expect(Object.keys(HELD).sort()).toEqual([...items].sort());
    for (const p of items) expect([p, ...HELD[p]]).toEqual([p, ...bases[p]]);
  });
  it('a hand fix is for a real pose, moves the anchor, and lands on an opaque pixel of that sprite', () => {
    for (const [p, [x, y]] of Object.entries(HEAD_FIX)) {
      expect(poses, p).toContain(p);
      expect([x, y], p).not.toEqual([...HEAD[p]]);
      expect(headOf(p), p).toEqual([x, y]);
      expect(alphaOf(new URL(`${p}.png`, DIR)).a(Math.floor(x), y), p).toBeGreaterThanOrEqual(128);
    }
    for (const p of poses) if (!HEAD_FIX[p]) expect(headOf(p), p).toEqual(HEAD[p]);
  });
});
