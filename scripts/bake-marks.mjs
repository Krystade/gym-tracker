// Bake the accessory placer's Copy into the app for everyone: writes src/domain/buddies/marks.ts, its Held marks as the app reads
// them (domain/buddies/guess learnFrom: the strip the app shows, frames past its end and marks that don't read left out) and the
// old stand-in slots (head, face, torso, legs, feet, hands) as they came, which nothing draws. The whole file is replaced: a Copy
// from the placer carries everything it shows, the baked marks included.
//
//   node scripts/bake-marks.mjs marks.json
//
// Then `UPDATE_PLACER=1 npx vitest run src/domain/buddies/guess.test.ts`, so the placer starts from them too.
import { readFileSync, writeFileSync } from 'node:fs';
import { learnFrom } from '../src/domain/buddies/guess.ts';

const file = process.argv[2];
if (!file) {
  console.error('Usage: node scripts/bake-marks.mjs marks.json   (marks.json: the accessory placer’s Copy)');
  process.exit(2);
}
const page = readFileSync(new URL('../public/tools/accessory-placer.html', import.meta.url), 'utf8');
const { world, buddies } = JSON.parse(page.split('\n').find((l) => l.startsWith('const APP = ')).slice('const APP = '.length, -1));
const copy = JSON.parse(readFileSync(file, 'utf8'));
const held = learnFrom(copy, world);

const key = (k) => (/^[a-z_$][\w$]*$/i.test(k) ? k : JSON.stringify(k));
const mark = (w) => `{ x: ${w.x}, y: ${w.y}, w: ${w.w}, h: ${w.h}, r: ${w.r}, f: ${w.f} }`;
const placed = buddies.filter((b) => held[b.id]).map((b) =>
  `  ${key(b.id)}: { ${Object.entries(held[b.id]).map(([f, w]) => `${f}: ${mark(w)}`).join(', ')} },`);

// A stand-in mark that is an empty object was never set: left out, as the placer leaves it.
const stand = [];
for (const [slot, ids] of Object.entries(copy)) {
  if (slot === 'held' || !ids || typeof ids !== 'object') continue;
  const rows = [];
  for (const [id, anims] of Object.entries(ids)) {
    const kept = Object.fromEntries(Object.entries(anims ?? {}).map(([a, fs]) => [a, Object.fromEntries(Object.entries(fs ?? {}).filter(([, v]) => v && Object.keys(v).length))]).filter(([, fs]) => Object.keys(fs).length));
    if (Object.keys(kept).length) rows.push(`    ${key(id)}: ${JSON.stringify(kept)},`);
  }
  if (rows.length) stand.push(`  ${key(slot)}: {\n${rows.join('\n')}\n  },`);
}

const frames = Object.values(held).reduce((n, fs) => n + Object.keys(fs).length, 0);
writeFileSync(new URL('../src/domain/buddies/marks.ts', import.meta.url), `// GENERATED by scripts/bake-marks.mjs from the accessory placer's Copy; bake a new Copy rather than edit this.
import type { Marks } from './guess';

/** The owner's Held marks, for everyone (${frames} frames on ${Object.keys(held).length} buddies): buddy → frame (a Tiny buddy's pose) → where the
 *  item's base sits, its size w × h, its tilt r° clockwise and whether it's mirrored, in the frame's own pixels (domain/buddies/guess
 *  Wear). They come before any guess; a frame not here is guessed from them. */
export const PLACED: Marks = {
${placed.join('\n')}
};

/** The old stand-in slots' marks (beanie, sunglasses and the rest), slot → buddy → strip → frame, as the placer saved them. The app
 *  has no such items, so nothing draws them: kept so they aren't lost. */
export const STAND_INS: Readonly<Record<string, Readonly<Record<string, Readonly<Record<string, Readonly<Record<string, { x: number; y: number; w: number; h?: number; r?: number; f?: boolean }>>>>>>>> = {
${stand.join('\n')}
};
`);
console.log(`Baked ${frames} Held frames on ${Object.keys(held).length} buddies, and the stand-in slots ${Object.keys(copy).filter((s) => s !== 'held').join(', ') || 'none'}.`);
